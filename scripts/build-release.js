import { mkdirSync, readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { buildSource } from './build-source.js';
import { verifyArtifact } from './package-artifact.js';
const root = resolve('.'), version = JSON.parse(readFileSync('package.json', 'utf8')).version;
mkdirSync('dist/releases', { recursive: true });
const release = mkdtempSync(resolve('dist/releases/' + version + '-'));
execFileSync(process.execPath, ['scripts/build-plugin.js', '--portable'], { stdio: 'inherit', windowsHide: true });
const source = buildSource(root, join(release, 'source'));
const artifact = verifyArtifact(resolve('dist/portable-marketplace/plugins/codex-continuer'));
const files = { source: 'continuer-' + version + '-source.tar.gz', windows: 'continuer-' + version + '-windows.zip' };
execFileSync('tar.exe', ['-czf', join(release, files.source), '-C', release, 'source'], { windowsHide: true });
execFileSync('tar.exe', ['-acf', join(release, files.windows), '-C', resolve('dist'), 'portable-marketplace'], { windowsHide: true });
const checksums = Object.fromEntries(Object.values(files).map(file => [file, createHash('sha256').update(readFileSync(join(release, file))).digest('hex')]));
const info = { version, buildId: artifact.buildId, sourceId: source.sourceId, protocolVersion: artifact.protocolVersion, files, checksums, signed: false };
writeFileSync(join(release, 'release.json'), JSON.stringify(info, null, 2));
writeFileSync(join(release, 'SHA256SUMS'), Object.entries(checksums).map(([file, hash]) => hash + '  ' + file).join('\n') + '\n');
console.log('Release prepared (not published): ' + release);
